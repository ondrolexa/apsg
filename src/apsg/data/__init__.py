"""Datasets bundled with APSG for examples, tutorials and reproducible tests.

```python
from apsg import data

data.catalog()                  # table of all datasets
data.info("fisher_1953")        # description and citation
f = data.load("faults")           # a FaultSet
smp = data.load("pmdata", site="PM04")   # a paleomagnetic Sample
data.path("structures")         # path of the file, e.g. for pandas
data.fisher_1953()              # same as data.load("fisher_1953")
```

The data are small, stored in the package and read with `importlib.resources`, so they
work from an installed wheel as well as from a checkout. Three groups exist:

* **tutorial data** (`faults`, `structures`, `structures_wide`, `pmdata`, `pmdata_sites`,
  `melechov`, `melechov_aex`, `trebic`, `trebic_aex`, `ams_table`, `ams_table_no_tensor`);
  `pmdata` is *artificial*: 71 specimens of 10 invented sites generated by
  a seeded random generator, following the physics of a thermal
  demagnetization experiment (a ChRM acquired before tilting, normal and reversed, a
  soft overprint, a few great-circle and poorly behaved specimens). Names, locations
  and numbers are invented, nothing comes from a real study. `melechov`,
  `melechov_aex`, `trebic`, `trebic_aex`, `ams_table` and `ams_table_no_tensor` are the opposite: real AMS
  measurements, the author's unpublished data;
* **published data**, short tables from textbooks and papers with the citation in
  `info()` (e.g. `fisher_1953`, `fle_b2`, `tauxe_table_4_2`, `gorleston_wind`);
* **synthetic data** with known properties (`fisher_k50`, `kent`, `watson_girdle`,
  `fold_data`, `ams_sites`, ...), generated with fixed seeds
  and stored, so they do not change with the random number generators of numpy.

Entries of kind `groups` return a dict of objects (for example `tauxe_table_4_2` gives
`{"normal": ..., "reversed": ...}`); `grouped` data (histogram counts) and tables
return a `pandas.DataFrame`. `ams_two_sites` (kind `ams`) gives a dict of
`apsg.ams.AMSSite` by site, with core orientation and bedding of every specimen.
"""

import pandas as pd

from apsg.data import _loaders as _L
from apsg.data._catalog import Dataset, loader, registry

__all__ = ["Dataset", "catalog", "info", "load", "names", "path", "pmd_file"]


def names():
    """Names of all datasets."""
    return list(registry())


def catalog():
    """Table of all datasets (name, kind, n, description, source)."""
    return pd.DataFrame(
        [
            {
                "name": d.name,
                "kind": d.kind,
                "n": d.n,
                "description": d.description,
                "source": d.source,
            }
            for d in registry().values()
        ]
    ).set_index("name")


def info(name):
    """``Dataset`` record of `name` (description, source, remarks)."""
    try:
        return registry()[name]
    except KeyError:
        raise KeyError(f"unknown dataset {name!r}, available: {names()}") from None


def load(name, **kwargs):
    """Load a dataset as apsg objects (see ``catalog()``).

    Every call returns new objects. ``pmdata`` takes ``site="PM04"`` to return one
    ``Sample`` instead of a dict of all of them; ``melechov`` and ``trebic`` take ``site="MEL1"`` and
    ``format="asc"`` or ``"ran"``.

    Args:
        name: dataset name.

    Returns:
        the data as ``FaultSet``, ``Vector3Set``, ``LineationSet``, ``FoliationSet``,
        ``Vector2Set``, ``EllipsoidSet``, ``Stress3Set`` or ``DataFrame``, a dict of
        those for kind ``groups``, or ``Sample`` objects for ``pmdata``.
    """
    info(name)
    return loader(name)(**kwargs)


def path(name):
    """Path of the file behind a dataset, for readers such as pandas.

    Works for the tutorial files (`faults`, `structures`, `structures_wide`);
    `pmdata`, `melechov` and `trebic` give the folder of their files (PMD; RAN, ASC and AEX)
    extracted once into the temporary directory. Datasets stored in the JSON catalogs have no file of their own.
    """
    d = info(name)
    if name == "pmdata":
        return _L.pmdata_folder()
    if name == "melechov":
        return _L.melechov_folder()
    if name == "trebic":
        return _L.trebic_folder()
    if d.file is None or d.file.endswith(".zip"):
        raise ValueError(f"{name!r} has no file of its own, use load({name!r})")
    return _L.file(d.file)


def pmd_file(specimen):
    """Path of the PMD file of a specimen of ``pmdata``, e.g. ``"PM01.1a"``."""
    p = _L.pmdata_folder() / f"{specimen}.pmd"
    if not p.exists():
        raise KeyError(f"unknown specimen {specimen!r}")
    return str(p)


def __getattr__(name):
    if name in registry():

        def _load(**kwargs):
            return load(name, **kwargs)

        _load.__name__ = name
        _load.__doc__ = str(info(name))
        return _load
    raise AttributeError(f"module 'apsg.data' has no attribute {name!r}")


def __dir__():
    return sorted([*__all__, *registry()])
